import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const manager = readFileSync(resolve(root, 'cbot/URMRLadderPositionManager.cs'), 'utf8');
const executor = readFileSync(resolve(root, 'cbot/URMDemoOneShotExecutor.cs'), 'utf8');
const observer = readFileSync(resolve(root, 'cbot/URMPositionObserver.cs'), 'utf8');
const guide = readFileSync(resolve(root, 'URM_R_LADDER_MANAGER_GUIDE.md'), 'utf8');

test('manager is Demo-only and refuses unsupported account model', () => {
  assert.match(manager, /Application\.EnvironmentType != EnvironmentType\.Desktop/);
  assert.match(manager, /if\s*\(Account\.IsLive\)/);
  assert.match(manager, /LIVE_ACCOUNT_NOT_ALLOWED/);
  assert.match(manager, /ACCOUNT_MODEL_UNSUPPORTED/);
  assert.match(manager, /Positions\.Opened \+= OnPositionOpened/);
});

test('manager only accepts the URM1 anchor label generated by the executor', () => {
  assert.match(executor, /BuildPositionLabel\(StructuralStopPrice, symbol\.Digits\)/);
  assert.match(executor, /URM1\|ID=/);
  assert.match(executor, /\|SL=/);
  assert.match(manager, /private const string LabelPrefix = "URM1\|"/);
  assert.match(manager, /TryParseAnchorLabel/);
  assert.match(manager, /position\.SymbolName, Symbol\.Name, StringComparison\.Ordinal/);
});

test('R ladder uses immutable structural SL and approved thresholds', () => {
  assert.match(manager, /private const double BreakEvenAtR = 1\.0/);
  assert.match(manager, /private const double LockAtR = 2\.0/);
  assert.match(manager, /private const double LockToR = 1\.7/);
  assert.match(manager, /private const double TrailingAtR = 3\.0/);
  assert.match(manager, /private const double TrailingGapR = 1\.0/);
  assert.match(manager, /private const double MinimumTrailingLockR = 2\.0/);
  assert.match(manager, /private const double TakeProfitR = 5\.0/);
  assert.match(manager, /var rDistance = Math\.Abs\(entry - structuralSL\)/);
});

test('manager persists high-water state before updates and refuses missing startup history', () => {
  assert.match(manager, /LocalStorage\.SetString/);
  assert.match(manager, /LocalStorage\.Flush\(LocalStorageScope\.Type\)/);
  assert.match(manager, /WritePeakState\(position, clientOrderId, structuralSL, peak, false\)/);
  assert.match(manager, /WritePeakState\(position, clientOrderId, structuralSL, peak, true\)/);
  assert.match(manager, /FlushPendingPeakState\("TIMER"\)/);
  assert.match(manager, /TryParsePeakRecord\(stored, position, clientOrderId, structuralSL, tickSize/);
  assert.match(manager, /does not match this exact position ID, symbol, side, entry and structural SL/);
  assert.match(manager, /PEAK_STATE_MISSING/);
  assert.match(manager, /POSITION_OPENED/);
  assert.match(manager, /PEAK_STATE_INVALID_OR_MISMATCHED/);
});

test('management is monotonic, uses fresh ticks and never changes TP or closes positions', () => {
  assert.match(manager, /MarketData\.GetTicks\(Symbol\.Name\)/);
  assert.match(manager, /MaximumTickAgeSeconds = 5/);
  assert.match(manager, /stopIsImprovement/);
  assert.match(manager, /ModifyPosition\(position, targetSL, position\.TakeProfit, ProtectionType\.Absolute, false, StopTriggerMethod\.Trade\)/);
  assert.match(manager, /readBackSL/);
  assert.match(manager, /readBackTP/);
  assert.doesNotMatch(manager, /ClosePosition\(/);
  assert.doesNotMatch(manager, /ExecuteMarketOrder\(/);
});

test('manager preserves TP and pauses at 5R or ambiguous protection', () => {
  assert.match(manager, /TP_BOUNDARY_RECONCILIATION_REQUIRED/);
  assert.match(manager, /TP_ANCHOR_MISMATCH/);
  assert.match(manager, /SERVER_SL_MISSING/);
  assert.match(manager, /SL_MODIFY_REJECTED/);
  assert.match(manager, /SL_SERVER_READBACK_MISMATCH/);
  assert.match(manager, /will not close it/);
});

test('guide requires local Demo, starts manager before executor and documents C# compile limitation', () => {
  assert.match(guide, /local cTrader desktop/i);
  assert.match(guide, /Start the manager \*\*before\*\* starting/);
  assert.match(guide, /has \*\*not\*\* been compiled or run against your installed cTrader Automate version/);
  assert.match(guide, /Do not use on Live/i);
  assert.match(observer, /READ_ONLY/);
});
